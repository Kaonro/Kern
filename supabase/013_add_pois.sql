-- Sommets, cols et points de vue OpenStreetMap (Overpass), importés une fois via script
-- plutôt qu'interrogés en direct à chaque visite : Overpass est un service public gratuit
-- régulièrement surchargé ("server too busy"), ce qui rendait la couche invisible de façon
-- intermittente. Pas d'écriture publique : seul un import ponctuel (SQL editor / service
-- role) alimente cette table, les visiteurs ne font que la lire.
create table public.pois (
  id bigint primary key, -- id du nœud OSM, réutilisé tel quel pour éviter les doublons au ré-import
  nom text not null,
  type text not null check (type in ('peak', 'col', 'viewpoint')),
  lat double precision not null,
  lng double precision not null,
  elevation_m integer,
  wikipedia_url text,
  created_at timestamptz not null default now()
);

alter table public.pois enable row level security;

create policy "Les sommets/cols/points de vue sont visibles par tous" on public.pois
  for select using (true);

